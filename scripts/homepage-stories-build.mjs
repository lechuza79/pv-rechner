// Rebuild the static homepage adapter from the same story components as dashboards.
import {build} from 'esbuild';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
await build({
 absWorkingDir:root,entryPoints:{'shared-story-cards':'scripts/homepage-stories/atlas-story-cards.jsx'},
 outdir:'public/homepage-study/story-dist',bundle:true,jsx:'automatic',format:'esm',
 // Keep CSS module names scoped; short names collide with the existing homepage bundles.
 minifyWhitespace:true,minifySyntax:true,minifyIdentifiers:false,
 external:['/fonts/*'],
 define:{'process.env.NODE_ENV':'"production"'},
 alias:{'next/link':root+'scripts/homepage-race/next-link.jsx','next/navigation':root+'scripts/homepage-race/next-navigation.js'},
});
// Keep the address used by the approved homepage package as a compatibility adapter.
await writeFile(root+'public/homepage-study/story-dist/atlas-story-cards.js',
 '// Generated by npm run homepage:stories; implementation is shared with dashboard and reader.\nexport {mountStoryCards} from "./shared-story-cards.js";\n');
